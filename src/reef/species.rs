//! Especies de arrecife del estilo realista: anatomía (perfil del cuerpo, aletas, cola) y coloración
//! natural. Las coordenadas de las marcas son (u, v): `u` va de la nariz (0) a la base de la cola
//! (1) y `v` de la panza (-1) al lomo (+1), relativo a la altura del cuerpo en cada punto.

use crate::draw::TailKind;
use crate::theme::Rgb;

pub struct RFin {
    pub u0: f64,
    pub u1: f64,
    /// Altura máxima respecto a la semialtura del cuerpo.
    pub h: f64,
    /// Cuánto se inclina hacia atrás (filamentos largos en los ángeles).
    pub lean: f64,
    /// Fracción delantera con radios espinosos.
    pub spiny: f64,
}

const fn fin(u0: f64, u1: f64, h: f64, lean: f64, spiny: f64) -> RFin {
    RFin { u0, u1, h, lean, spiny }
}

pub enum Mark {
    /// Banda vertical (como las del pez payaso), con borde opcional.
    Bar { u: f64, w: f64, col: Rgb, edge: Option<Rgb>, slant: f64, a: f64 },
    /// Mancha de forma libre (la "paleta" del cirujano azul, los remolinos del mandarín).
    Patch { pts: &'static [(f64, f64)], col: Rgb, a: f64 },
    /// Raya longitudinal.
    Stripe { v: f64, w: f64, u0: f64, u1: f64, col: Rgb, a: f64 },
    Spots { n: u32, r: f64, u0: f64, u1: f64, v0: f64, v1: f64, col: Rgb, a: f64 },
    /// Cambio de color a partir de `u` (gramma real: morado delante, amarillo detrás).
    TwoTone { u: f64, soft: f64, col: Rgb, a: f64 },
    /// Líneas diagonales finas (peces mariposa).
    Lines { n: u32, u0: f64, u1: f64, slope: f64, w: f64, col: Rgb, a: f64 },
}

pub struct RSpecies {
    pub name: &'static str,
    /// Semialtura máxima del cuerpo / longitud total.
    pub ratio: f64,
    pub tail_frac: f64,
    pub tail: TailKind,
    /// Apertura de la cola / su longitud.
    pub spread: f64,
    pub prof: &'static [(f64, f64)],
    /// Cuánto ondula el cuerpo al nadar (los discos casi no, usan las pectorales).
    pub bend: f64,
    pub back: Rgb,
    pub mid: Rgb,
    pub belly: Rgb,
    pub fin: Rgb,
    pub fin_a: f64,
    pub fin_edge: Option<Rgb>,
    pub tail_col: Rgb,
    pub dorsal: RFin,
    pub dorsal2: Option<RFin>,
    pub anal: RFin,
    pub pelvic: f64,
    pub pect: f64,
    pub pect_h: f64,
    pub eye: f64,
    pub eye_u: f64,
    pub iris: Rgb,
    pub scale: f64,
    pub scale_col: Option<Rgb>,
    pub gloss: f64,
    pub irid: Option<(Rgb, f64)>,
    pub marks: &'static [Mark],
}

